import numpy as np

# 1. Tinh vector gradient bang sai phan huu han
def tinh_gradient(ham_so, diem_x, h=1e-5):
    so_chieu = len(diem_x)
    gradient = np.zeros(so_chieu)

    for i in range(so_chieu):
        vector_don_vi = np.zeros(so_chieu)
        vector_don_vi[i] = h

        gradient[i] = (ham_so(diem_x + vector_don_vi) - ham_so(diem_x - vector_don_vi)) / (2 * h)

    return gradient

# 2. Tinh ma tran Hessian
def tinh_hessian(ham_so, diem_x, h=1e-4):
    so_chieu = len(diem_x)
    ma_tran_hessian = np.zeros((so_chieu, so_chieu))
    gia_tri_ham = ham_so(diem_x)

    for i in range(so_chieu):
        vector_i = np.zeros(so_chieu)
        vector_i[i] = h

        # Tinh cac phan tu tren duong cheo
        ma_tran_hessian[i, i] = (ham_so(diem_x + vector_i) - 2 * gia_tri_ham + ham_so(diem_x - vector_i)) / h**2

        # Tinh cac phan tu ngoai duong cheo
        for j in range(i + 1, so_chieu):
            vector_j = np.zeros(so_chieu)
            vector_j[j] = h

            gia_tri = (ham_so(diem_x + vector_i + vector_j)
                - ham_so(diem_x + vector_i - vector_j)
                - ham_so(diem_x - vector_i + vector_j)
                + ham_so(diem_x - vector_i - vector_j)) / (4 * h**2)

            ma_tran_hessian[i, j] = gia_tri
            ma_tran_hessian[j, i] = gia_tri

    return ma_tran_hessian

# 3. Thuat toan Newton-Raphson tim diem dung
def newton_raphson(ham_so, diem_ban_dau,
                   sai_so=1e-8, so_lan_lap_toi_da=100):

    diem_x = np.array(diem_ban_dau, dtype=float)

    for lan_lap in range(so_lan_lap_toi_da):
        gradient = tinh_gradient(ham_so, diem_x)

        # Dung neu gradient du nho
        if np.linalg.norm(gradient) < sai_so:
            return diem_x, ham_so(diem_x), lan_lap, "Hoi tu"

        ma_tran_hessian = tinh_hessian(ham_so, diem_x)

        try:
            # Giai he phuong trinh Hessian * buoc = gradient
            buoc_nhay = np.linalg.solve(
                ma_tran_hessian, gradient
            )
        except np.linalg.LinAlgError:
            return (
                diem_x, ham_so(diem_x),
                lan_lap, "Hessian suy bien"
            )

        # Cap nhat diem x theo cong thuc Newton-Raphson
        diem_x = diem_x - buoc_nhay

        # Kiem tra ket qua co phai so huu han hay khong
        if not np.all(np.isfinite(diem_x)):
            return diem_x, float("nan"), lan_lap + 1, "Khong hoi tu"

    return (
        diem_x, ham_so(diem_x),
        so_lan_lap_toi_da, "Dat gioi han lap"
    )

# 4. Phan loai diem dung dua tren tri rieng Hessian
def phan_loai_diem(ham_so, diem_x):
    ma_tran_hessian = tinh_hessian(ham_so, diem_x)
    tri_rieng = np.linalg.eigvalsh(ma_tran_hessian)

    if np.all(tri_rieng > 1e-6):
        loai_diem = "Cuc tieu dia phuong"
    elif np.all(tri_rieng < -1e-6):
        loai_diem = "Cuc dai dia phuong"
    else:
        loai_diem = "Diem yen ngua hoac chua ket luan"

    return loai_diem, tri_rieng

# 5. Vi du tim cuc tieu
# Ham so: f(x, y) = (x - 2)^2 + 3(y + 1)^2
def ham_cuc_tieu(diem_x):
    return (diem_x[0] - 2)**2 + 3 * (diem_x[1] + 1)**2

diem_x, gia_tri, so_lan_lap, trang_thai = newton_raphson(
    ham_cuc_tieu, [0, 0]
)

print("TIM CUC TIEU")
print("Trang thai:", trang_thai)
print("Diem tim duoc:", diem_x)
print("Gia tri ham so:", gia_tri)
print("So lan lap:", so_lan_lap)
print("Phan loai:", phan_loai_diem(ham_cuc_tieu, diem_x)[0])

# 6. Vi du tim cuc dai
# Ham so: g(x, y) = -x^2 - 2y^2
def ham_cuc_dai(diem_x):
    return -diem_x[0]**2 - 2 * diem_x[1]**2

diem_x, gia_tri, so_lan_lap, trang_thai = newton_raphson(
    ham_cuc_dai, [1, -1]
)

print("\nTIM CUC DAI")
print("Trang thai:", trang_thai)
print("Diem tim duoc:", diem_x)
print("Gia tri ham so:", gia_tri)
print("So lan lap:", so_lan_lap)
print("Phan loai:", phan_loai_diem(ham_cuc_dai, diem_x)[0])