#Thu thập dữ liệu từ https://quotes.toscrape.com
import json
import time

import requests
from bs4 import BeautifulSoup

BASE_URL = "https://quotes.toscrape.com"
OUTPUT_FILE = "data.json"
MIN_ITEMS = 100

def scrape_page(page):
    url = f"{BASE_URL}/" if page == 1 else f"{BASE_URL}/page/{page}/"
    response = requests.get(url, timeout=10)
    response.raise_for_status()
    soup = BeautifulSoup(response.text, "html.parser")

    items = []
    for quote in soup.select(".quote"):
        items.append({
            "text": quote.select_one(".text").get_text(strip=True),
            "author": quote.select_one(".author").get_text(strip=True),
            "tags": [t.get_text(strip=True) for t in quote.select(".tag")],
        })
    has_next = soup.select_one("li.next a") is not None
    return items, has_next

def main():
    data = []
    page = 1
    while True:
        print(f"Đang cào trang {page}")
        items, has_next = scrape_page(page)
        data.extend(items)
        if not has_next:
            break
        page += 1

    for i, item in enumerate(data, 1):
        item["id"] = i

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Đã lưu dữ liệu vào {OUTPUT_FILE}")

main()